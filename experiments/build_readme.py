"""Render README.md from docs/README.template.md.

    uv run python experiments/build_readme.py

Every number in the README is a placeholder {{Name}} filled from results/theory_constants.json,
which experiments/theory_tables.py generates from results/*.json (the same values the theory
PDF uses). An unknown placeholder is an error. tests/test_readme.py fails if README.md is out of
date, so a number cannot drift from its results file unnoticed.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "docs" / "README.template.md"
HEADER = ("<!-- Generated by experiments/build_readme.py from docs/README.template.md and "
          "results/theory_constants.json. Edit the template, not this file. -->\n")


def _plain(latex: str) -> str:
    """LaTeX-formatted constant -> Markdown text."""
    text = re.sub(r"\\text\{([^}]*)\}", r"\1", latex)
    return (text.replace("{,}", ",").replace(r"\infty", "∞").replace(r"\%", "%")
            .replace("--", "–").replace("$", ""))


def render() -> str:
    constants = json.loads((ROOT / "results" / "theory_constants.json").read_text())
    text = TEMPLATE.read_text()

    def sub(m: re.Match) -> str:
        name = m.group(1)
        if name not in constants:
            raise KeyError(f"unknown placeholder {{{{{name}}}}} in {TEMPLATE.name}")
        return _plain(constants[name]["value"])

    return HEADER + re.sub(r"\{\{(\w+)\}\}", sub, text)


def main() -> None:
    (ROOT / "README.md").write_text(render())
    print("wrote README.md")


if __name__ == "__main__":
    main()
